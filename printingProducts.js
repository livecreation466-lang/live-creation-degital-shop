export const buildWhatsAppLink = (product, finish, qty) => {
  const text = `Hi Live Creation, I want to inquire about *${product.name}*%0A%0AFinish: ${finish}%0AQuantity/Size: ${qty}%0A%0APlease share details & pricing.`;
  return `https://wa.me/${BUSINESS.whatsapp}?text=${text}`;
};

export const buildEmailLink = (product, finish, qty) => {
  const subject = encodeURIComponent(`Quote Request — ${product.name}`);
  const body = encodeURIComponent(
    `Hi Live Creation,\n\nI would like a quote for:\n\nProduct: ${product.name}\nFinish: ${finish}\nQuantity/Size: ${qty}\n\nPlease share pricing and delivery timeline.\n\nThanks!`
  );
  return `mailto:${BUSINESS.email}?subject=${subject}&body=${body}`;
};

